def _fp(climate, **overrides):
    """Build fingerprint: climate base + per-field overrides."""
    fp = {}
    for field in ALL_FIELDS:
        fp[field] = dict(BASE[climate][field])  # copy base
        if field in overrides:
            fp[field] = overrides[field]  # replace entirely
    return fp

def _r(lat, lng, radius, elev_lo, elev_hi, temp_lo, temp_hi, humid_lo, humid_hi, name, climate, **fp_overrides):
    return {
        "id": "", "name": name,
        "center_lat": lat, "center_lng": lng, "radius_km": radius,
        "elevation_range": [elev_lo, elev_hi],
        "temp_range": [temp_lo, temp_hi],
        "humid_range": [humid_lo, humid_hi],
        "fingerprint": _fp(climate, **fp_overrides),
    }


